export const BUSAN_PASS_MAP_CENTER = { lat: 35.1733, lng: 129.0839 }

type BusanPassMapBasePlace = Omit<MapPlace, 'description'> & {
  description: string
  ticketTitle?: string
  naverMapUrl?: string
  relatedTicketTag?: string
}

function passRelatedTicketHref(tag: string, placeId: string): string {
  return `/busan/ticket?tag=${encodeURIComponent(tag)}&from=pass-map&place=${encodeURIComponent(placeId)}#ticketListTitle`
}

function ticketActions(title: string, placeId: string) {
  const card = busanTicketCards.find((item) => item.title.trim() === title.trim())
  if (!card) return undefined
  return (card.actions as CityCardAction[]).map((action) => ({
    ...action,
    mapEvent:
      action.mapEvent?.replace(/^busanmap_/, 'busanpassmap_') ??
      action.event?.replace(/^busanticket_/, 'busanpassmap_ticket_') ??
      `busanpassmap_${placeId}_${action.label.toLowerCase()}`,
  }))
}

function naverActions(place: BusanPassMapBasePlace): CityCardAction[] {
  const href = place.naverMapUrl?.trim()
  if (!href) return []
  return [
    {
      label: 'NaverMap',
      href,
      mapEvent: `busanpassmap_${place.id}_naver`,
      platform: 'NaverMap',
    },
  ]
}

